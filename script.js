function generateQuote() {
  currentIndex = Math.floor(Math.random() * sentences.length);

  currentQuote = sentences[currentIndex];

  quoteDisplay.textContent = currentQuote;
  quoteDisplay.classList.remove("empty");

  copyBtn.textContent = "COPY";
}

function copyQuote() {
  if (!currentQuote) {
    alert("Please generate a sentence first!");
    return;
  }

  navigator.clipboard.writeText(currentQuote)
    .then(() => {
      copyBtn.textContent = "COPIED ✓";

      setTimeout(() => {
        copyBtn.textContent = "COPY";
      }, 1800);
    })
    .catch(() => {
      const textarea = document.createElement("textarea");

      textarea.value = currentQuote;

      document.body.appendChild(textarea);

      textarea.select();

      document.execCommand("copy");

      textarea.remove();

      copyBtn.textContent = "COPIED ✓";

      setTimeout(() => {
        copyBtn.textContent = "COPY";
      }, 1800);
    });
}